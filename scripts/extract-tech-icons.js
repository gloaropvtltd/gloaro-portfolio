import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const iconsDir = path.join(__dirname, "..", "node_modules", "simple-icons", "icons");
const dataFile = path.join(__dirname, "..", "node_modules", "simple-icons", "data", "simple-icons.json");

const needed = {
  react: "react",
  nextdotjs: "nextdotjs",
  javascript: "javascript",
  tailwindcss: "tailwindcss",
  nodedotjs: "nodedotjs",
  nestjs: "nestjs",
  laravel: "laravel",
  postgresql: "postgresql",
  mysql: "mysql",
  vercel: "vercel",
  googlecloud: "googlecloud",
  cloudflare: "cloudflare",
  docker: "docker",
  githubactions: "githubactions",
  claude: "claude",
  googlegemini: "googlegemini",
  langchain: "langchain",
  python: "python",
  flutter: "flutter",
  supabase: "supabase",
};

const parsed = JSON.parse(readFileSync(dataFile, "utf8"));
const icons = parsed.icons ?? parsed;
const bySlug = new Map(icons.map((icon) => [icon.slug ?? icon.title.toLowerCase().replace(/\s+/g, ""), icon]));

const result = {};
for (const [key, slug] of Object.entries(needed)) {
  const svg = readFileSync(path.join(iconsDir, `${slug}.svg`), "utf8");
  const match = svg.match(/<path d="([^"]+)"/);
  const meta = bySlug.get(slug);
  result[key] = {
    path: match[1],
    hex: meta?.hex ?? "000000",
    title: meta?.title ?? key,
  };
}

// React Native uses the same atom logo as React — no separate simple-icons entry.
result.reactnative = { ...result.react, title: "React Native" };

// AWS has no logo in the current simple-icons release (removed, same as OpenAI).
// Rendered as a text-only badge instead of fabricating a logo.
result.aws = { path: null, hex: null, title: "AWS" };

const out = `// Generated by scripts/extract-tech-icons.js from the simple-icons package.
// Do not hand-edit — re-run the script if the icon set changes.
export const techIcons = ${JSON.stringify(result, null, 2)};
`;

writeFileSync(path.join(__dirname, "..", "src", "data", "techIcons.js"), out);
console.log(`Extracted ${Object.keys(result).length} icons.`);
